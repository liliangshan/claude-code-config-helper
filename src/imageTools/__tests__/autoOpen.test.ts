/** @file Generated image editor auto-open tests use temporary files and stubbed VS Code commands only. */
import assert from 'node:assert/strict';
import { test } from 'node:test';
import * as fs from 'node:fs/promises';
import * as os from 'node:os';
import * as path from 'node:path';
import { randomUUID } from 'node:crypto';
import { pathToFileURL } from 'node:url';
import { installVscodeStub } from '../../chat/__tests__/testUtils/vscodeStub';
import { defaultImageConfig, type ImageTask } from '../types';
import type { ConfigManager } from '../../configManager';

const settings = installVscodeStub({ values: { claudeCodeConfigHelper: {} } });
const vscode = require('vscode');
vscode.commands = { executeCommand: async () => {} };
const { ImageToolHost } = require('../imageToolHost') as typeof import('../imageToolHost');
const png = Buffer.from('89504e470d0a1a0a', 'hex');

/** Build a remote resource preserving authority and URI path independently of its canonical filesystem path. */
function remoteUri(fsPath: string, uriPath: string): any {
    return { scheme: 'vscode-remote', authority: 'ssh-remote+fixture', path: uriPath, fsPath,
        toString: () => `vscode-remote://ssh-remote+fixture${uriPath.split('/').map(encodeURIComponent).join('/')}` };
}

/** Prepare a real task queue with local generated bytes and capture all editor-open requests. */
async function fixture() {
    const root = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'image-auto-open-')));
    settings.values.claudeCodeConfigHelper = {};
    const records = new Map<string, unknown>(), secrets = new Map<string, string>();
    const context = { globalStorageUri: { fsPath: root }, secrets: { get: async (key: string) => secrets.get(key), store: async (key: string, value: string) => { secrets.set(key, value); }, delete: async (key: string) => { secrets.delete(key); } },
        workspaceState: { get: (key: string, fallback: unknown) => records.get(key) ?? fallback, update: async (key: string, value: unknown) => { records.set(key, value); } } } as unknown as import('vscode').ExtensionContext;
    const manager = { listProviders: () => [], onDidChange: () => ({ dispose() {} }), getResolvedUiLanguage: () => 'en' } as unknown as ConfigManager;
    vscode.workspace.isTrusted = true;
    let folders = [{ uri: { fsPath: root, scheme: 'file' } }];
    Object.defineProperty(vscode.workspace, 'workspaceFolders', { configurable: true, get: () => folders });
    vscode.Uri.file = (file: string) => ({ scheme: 'file', fsPath: file, toString: () => pathToFileURL(file).toString() });
    vscode.Uri.joinPath = (uri: any, ...parts: string[]) => remoteUri(path.join(uri.fsPath, ...parts), path.posix.join(uri.path, ...parts));
    const opens: any[][] = [];
    vscode.commands.executeCommand = async (...args: unknown[]) => { opens.push(args); };
    const host = new ImageToolHost(context, manager);
    await host.initialize();
    await host.config.save({ expectedRevision: 0, config: { ...defaultImageConfig(), enabled: true, modelId: 'fixture', baseUrl: 'https://example.com', authMode: 'none' }, keyAction: 'keep' });
    const scope = { cwd: root, id: 'a'.repeat(64), title: 'Image task' };
    const queue = await (host as any).queue(root);
    let providerCalls = 0;
    queue.client.generate = async () => { providerCalls++; return [{}]; };
    queue.client.load = async () => png;
    const opening: Promise<void>[] = [];
    const open = (host as any).autoOpenImages.bind(host);
    (host as any).autoOpenImages = (cwd: string, task: ImageTask) => { const action = open(cwd, task); opening.push(action); return action; };
    return {
        root, host, scope, queue, opens, opening,
        providerCalls: () => providerCalls,
        setFolders: (value: typeof folders) => { folders = value; },
        /** Submit one mocked task and await its real completion event plus editor actions. */
        async submit(edit = false): Promise<ImageTask> {
            const source = path.join(root, 'reference.png'); if (edit) await fs.writeFile(source, png);
            const response = await host.execute(scope, edit ? 'openapi_edit_image' : 'openapi_generate_image', { prompt: 'test', size: '1024x1024', ...(edit ? { image: source } : {}) }, randomUUID(), () => true);
            assert.equal(response.isError, undefined, JSON.stringify(response));
            const taskId = JSON.parse(String(response.content[0].text)).taskId;
            await queue.idle(); await Promise.all(opening);
            return queue.store.get(scope.id, taskId);
        },
        /** Close the host before deleting only this test's temporary directory. */
        async close(): Promise<void> { await host.close(); await Promise.all(opening); await fs.rm(root, { recursive: true, force: true }); }
    };
}

test('newly generated and edited images open as pinned editor tabs without waiting for a chat view', async () => {
    const f = await fixture();
    try {
        const generated = await f.submit(), edited = await f.submit(true);
        assert.equal(f.opens.length, 2); assert.equal(f.providerCalls(), 2);
        for (const [index, task] of [generated, edited].entries()) {
            assert.equal(task.status, 'succeeded');
            assert.equal(f.opens[index][0], 'vscode.open');
            assert.equal(f.opens[index][1].fsPath, path.join(f.root, '.LLSOAI/openapi-image-generation', task.images[0].relativePath));
            assert.deepEqual(f.opens[index][2], { preview: false, preserveFocus: true });
        }
    } finally { await f.close(); }
});

test('multiple saved images open once even when the task partially fails or completion is repeated', async () => {
    const f = await fixture();
    try {
        f.queue.client.generate = async () => [{}, null, {}];
        f.queue.client.load = async (item: unknown) => { if (item === null) throw new Error('Invalid image'); return png; };
        const task = await f.submit();
        assert.equal(task.status, 'partially_failed'); assert.equal(f.opens.length, 2);
        await Promise.all([(f.host as any).autoOpenImages(f.root, task), (f.host as any).autoOpenImages(f.root, task)]);
        await f.host.receive({ type: 'imageGeneration/tasksList', requestId: 'history' }, { scope: async () => f.scope, post() {} });
        await f.host.execute(f.scope, 'openapi_get_image_task', { taskId: task.taskId }, randomUUID(), () => true);
        await f.host.initialize();
        assert.equal(f.opens.length, 2, 'History/queries/reinitialization must not reopen generated images');
    } finally { await f.close(); }
});

test('automatic image opening respects the master auto-open switch but not the code-preview switch', async () => {
    const f = await fixture();
    try {
        settings.values.claudeCodeConfigHelper['editor.codePreview.enabled'] = false;
        settings.values.claudeCodeConfigHelper['editor.autoOpenReadWriteFiles'] = false;
        const task = await f.submit(); assert.equal(f.opens.length, 0);
        await f.host.receive({ type: 'imageGeneration/imageOpen', requestId: 'manual', taskId: task.taskId, imageId: task.images[0].id }, { scope: async () => f.scope, post() {} });
        assert.equal(f.opens.length, 1, 'Explicit image opening remains available');
        settings.values.claudeCodeConfigHelper['editor.autoOpenReadWriteFiles'] = true;
        await f.submit(); assert.equal(f.opens.length, 2);
    } finally { await f.close(); }
});

test('remote generated images retain workspace authority and URI path instead of opening local file URLs', async () => {
    const f = await fixture();
    try {
        f.setFolders([{ uri: remoteUri(f.root, '/remote/项目 # folder') }]);
        const task = await f.submit(); const uri = f.opens[0][1];
        assert.equal(uri.scheme, 'vscode-remote'); assert.equal(uri.authority, 'ssh-remote+fixture');
        assert.equal(uri.path, '/remote/项目 # folder/.LLSOAI/openapi-image-generation/' + task.images[0].relativePath);
        assert.ok(uri.toString().includes('%23')); assert.ok(uri.toString().includes('%20'));
        await f.host.receive({ type: 'imageGeneration/imageOpen', requestId: 'manual-remote', taskId: task.taskId, imageId: task.images[0].id }, { scope: async () => f.scope, post() {} });
        assert.equal(f.opens[1][1].toString(), uri.toString());
    } finally { await f.close(); }
});

test('SVG results open in the default text editor for automatic and explicit actions', async () => {
    const f = await fixture();
    try {
        const config = await f.host.config.read();
        await f.host.config.save({ expectedRevision: config.revision, keyAction: 'keep', config: { ...config, supportsPng: false, supportsSvg: true } });
        f.queue.client.load = async () => Buffer.from('<svg xmlns="http://www.w3.org/2000/svg"><rect width="10" height="10"/></svg>');
        const task = await f.submit();
        assert.equal(task.status, 'succeeded'); assert.equal(task.output_format, 'svg');
        assert.equal(f.opens[0][0], 'vscode.openWith'); assert.equal(f.opens[0][2], 'default');
        assert.deepEqual(f.opens[0][3], { preview: false, preserveFocus: true });
        await f.host.receive({ type: 'imageGeneration/imageOpen', requestId: 'svg-manual', taskId: task.taskId, imageId: task.images[0].id }, { scope: async () => f.scope, post() {} });
        assert.equal(f.opens[1][0], 'vscode.openWith'); assert.equal(f.opens[1][2], 'default');
        assert.equal(f.providerCalls(), 1);
    } finally { await f.close(); }
});

test('failed tasks and editor command failures never replay generation or change successful image results', async () => {
    const f = await fixture();
    try {
        let attempts = 0;
        vscode.commands.executeCommand = async () => { attempts++; throw new Error('Editor unavailable'); };
        const task = await f.submit();
        assert.equal(task.status, 'succeeded'); assert.equal(attempts, 1); assert.equal(f.providerCalls(), 1);
        await (f.host as any).autoOpenImages(f.root, task); assert.equal(attempts, 1);
        f.queue.client.generate = async () => { throw new Error('Provider unavailable'); };
        const failed = await f.submit(); assert.equal(failed.status, 'failed'); assert.equal(attempts, 1);
    } finally { await f.close(); }
});

test('auto-open validates ownership and files and stops when trust is removed or the host closes', async () => {
    const f = await fixture();
    try {
        settings.values.claudeCodeConfigHelper['editor.autoOpenReadWriteFiles'] = false;
        const task = await f.submit();
        settings.values.claudeCodeConfigHelper['editor.autoOpenReadWriteFiles'] = true;
        (f.host as any).openedImages.clear();
        await (f.host as any).autoOpenImages(f.root, { ...task, scopeId: 'b'.repeat(64) });
        assert.equal(f.opens.length, 0);
        const file = path.join(f.root, '.LLSOAI/openapi-image-generation', task.images[0].relativePath);
        await fs.unlink(file);
        await (f.host as any).autoOpenImages(f.root, task); assert.equal(f.opens.length, 0);
        (f.host as any).openedImages.clear(); await fs.writeFile(file, png);
        const original = (f.host as any).imageUri.bind(f.host);
        (f.host as any).imageUri = async (filename: string) => { const uri = await original(filename); vscode.workspace.isTrusted = false; return uri; };
        await (f.host as any).autoOpenImages(f.root, task); assert.equal(f.opens.length, 0);
        vscode.workspace.isTrusted = true; await f.host.close();
        await (f.host as any).autoOpenImages(f.root, task); assert.equal(f.opens.length, 0);
    } finally { await f.close(); }
});
